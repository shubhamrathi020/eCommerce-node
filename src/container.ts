import { AccountsService } from './accounts/accounts-service';
import { AddressesService } from './addresses/addresses-service';
import { AuthService } from './auth/auth-service';
import { MailService } from './auth/mail';
import { PasswordService } from './auth/password';
import { TokenService } from './auth/tokens';
import { CacheService } from './cache/cache';
import { CouponRedemptionService } from './cache/coupon-redemption';
import { RateLimitGuard } from './cache/rate-limit';
import { RedisService } from './cache/redis';
import { AdminCatalogService } from './catalog/admin-catalog-service';
import { CatalogService } from './catalog/catalog-service';
import { MongoService } from './catalog/mongo';
import { SearchService } from './catalog/search-service';
import { AdminOrderService } from './commerce/admin-order-service';
import { CartService } from './commerce/cart-service';
import { InventoryService } from './commerce/inventory';
import { OrderService } from './commerce/order-service';
import { PaymentService } from './commerce/payment-service';
import { RazorpayService } from './commerce/razorpay';
import type { ApiConfig } from './config';
import { Db } from './db/prisma';
import { Throttler } from './http/throttle';
import { NotificationConsumerService } from './messaging/notification-consumer';
import { OrderEventsService } from './messaging/order-events';
import { OutboxRelayService } from './messaging/outbox-relay';
import { OutboxService } from './messaging/outbox';
import { RabbitService } from './messaging/rabbit';
import { SchedulerService } from './messaging/scheduler';
import { MetricsService } from './metrics/metrics';

/** Every service of the app, built once and wired by hand (there is no dependency-injection framework). */
export interface Services {
  config: ApiConfig;
  db: Db;
  redis: RedisService;
  cache: CacheService;
  coupons: CouponRedemptionService;
  rateLimits: RateLimitGuard;
  throttler: Throttler;
  mongo: MongoService;
  search: SearchService;
  mail: MailService;
  passwords: PasswordService;
  tokens: TokenService;
  auth: AuthService;
  accounts: AccountsService;
  addresses: AddressesService;
  catalog: CatalogService;
  adminCatalog: AdminCatalogService;
  cart: CartService;
  inventory: InventoryService;
  rabbit: RabbitService;
  outbox: OutboxService;
  orderEvents: OrderEventsService;
  orders: OrderService;
  razorpay: RazorpayService;
  payments: PaymentService;
  adminOrders: AdminOrderService;
  relay: OutboxRelayService;
  consumer: NotificationConsumerService;
  scheduler: SchedulerService;
  metrics: MetricsService;
}

export function buildServices(config: ApiConfig): Services {
  const db = new Db(config.databaseUrl);
  const redis = new RedisService(config);
  const cache = new CacheService(redis);
  const coupons = new CouponRedemptionService(redis);
  const rateLimits = new RateLimitGuard(config, redis, cache);
  const throttler = new Throttler(config.rateLimit);
  const mongo = new MongoService(config);
  const search = new SearchService(config);
  const mail = new MailService(config);
  const passwords = new PasswordService();
  const tokens = new TokenService(config, db);
  const auth = new AuthService(db, passwords, tokens, mail);
  const accounts = new AccountsService(db, passwords, tokens);
  const addresses = new AddressesService(db);
  const catalog = new CatalogService(mongo, search, cache);
  const adminCatalog = new AdminCatalogService(mongo, search, cache);
  const cart = new CartService(db, mongo);
  const inventory = new InventoryService(mongo, cache);
  const rabbit = new RabbitService(config);
  const outbox = new OutboxService(db);
  const orderEvents = new OrderEventsService(redis, config);
  const orders = new OrderService(db, cart, inventory, coupons, outbox, orderEvents);
  const razorpay = new RazorpayService(config);
  const payments = new PaymentService(db, orders, cart, inventory, razorpay, outbox, orderEvents, config);
  const adminOrders = new AdminOrderService(db, orders, inventory, razorpay, coupons, outbox, orderEvents);
  const relay = new OutboxRelayService(db, rabbit, redis);
  const consumer = new NotificationConsumerService(rabbit, mail, redis);
  const scheduler = new SchedulerService(db, redis, orders, outbox, config);
  const metrics = new MetricsService(cache, razorpay, search, db);
  return { config, db, redis, cache, coupons, rateLimits, throttler, mongo, search, mail, passwords, tokens, auth, accounts, addresses, catalog, adminCatalog, cart, inventory, rabbit, outbox, orderEvents, orders, razorpay, payments, adminOrders, relay, consumer, scheduler, metrics };
}
